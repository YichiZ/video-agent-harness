"""Write the `WS /chat` frames in `server.api.protocol` to `web/src/protocol.ts`.

uv run python scripts/export_protocol.py           # write the file
uv run python scripts/export_protocol.py --check   # exit 1 if it is out of date
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from server.api import protocol  # noqa: E402

OUT = ROOT / "web" / "src" / "protocol.ts"
CLIENT = [protocol.UserMessage, protocol.Interrupt]
PARTS = [protocol.ToolCall, protocol.ChatTurn]  # nested in History
SERVER = [
    protocol.History,
    protocol.TextDelta,
    protocol.ToolUse,
    protocol.ToolResult,
    protocol.Result,
    protocol.ChatTitle,
    protocol.IngestStatus,
    protocol.ChatError,
]


def ts_type(schema: dict) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if schema.get("type") == "array":
        return f"{ts_type(schema['items'])}[]"
    if "const" in schema:
        return f'"{schema["const"]}"'
    if "anyOf" in schema:
        return " | ".join(ts_type(s) for s in schema["anyOf"])
    kind = schema.get("type")
    if kind == "object":
        extra = schema.get("additionalProperties")
        return f"Record<string, {ts_type(extra) if isinstance(extra, dict) else 'unknown'}>"
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean",
            "null": "null"}.get(kind, "unknown")  # fmt: skip


def interface(model) -> str:
    schema = model.model_json_schema()
    lines = [f"export interface {model.__name__} {{"]
    for name, prop in schema["properties"].items():
        lines.append(f"  {name}: {ts_type(prop)};")  # the server always sends defaults
    return "\n".join([*lines, "}"])


def render() -> str:
    parts = [
        "// Generated by scripts/export_protocol.py from server/api/protocol.py. Do not edit.",
        *(interface(m) for m in CLIENT + PARTS + SERVER),
        "export type ClientFrame = " + " | ".join(m.__name__ for m in CLIENT) + ";",
        "export type ServerFrame = " + " | ".join(m.__name__ for m in SERVER) + ";",
    ]
    return "\n\n".join(parts) + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not OUT.is_file() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run scripts/export_protocol.py")
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
